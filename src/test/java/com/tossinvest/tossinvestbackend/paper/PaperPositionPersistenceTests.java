package com.tossinvest.tossinvestbackend.paper;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.autoconfigure.domain.EntityScan;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;
import org.springframework.context.annotation.Configuration;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;

import java.math.BigDecimal;
import java.nio.file.Path;
import java.sql.DriverManager;
import java.time.LocalDate;

import static org.assertj.core.api.Assertions.assertThat;

class PaperPositionPersistenceTests {
    @TempDir Path directory;

    @Configuration(proxyBeanMethods = false)
    @EnableAutoConfiguration
    @EntityScan(basePackageClasses = PaperPosition.class)
    @EnableJpaRepositories(basePackageClasses = PaperPositionRepository.class)
    static class App {}

    private String url() { return "jdbc:h2:file:" + directory.resolve("positions").toAbsolutePath(); }

    private ConfigurableApplicationContext open(String ddl) {
        return new SpringApplicationBuilder(App.class).web(WebApplicationType.NONE).run(
                "--spring.datasource.url=" + url(), "--spring.datasource.username=sa", "--spring.datasource.password=",
                "--spring.jpa.hibernate.ddl-auto=" + ddl, "--spring.jpa.show-sql=false", "--spring.main.banner-mode=off");
    }

    private PaperPosition position(String rate) {
        return PaperPosition.builder().symbol("005930").entryDate(LocalDate.of(2026, 10, 8))
                .entryPrice(new BigDecimal("100000")).status("CLOSED")
                .exitDate(LocalDate.of(2026, 10, 9)).exitPrice(new BigDecimal("101234.50"))
                .peakRate(new BigDecimal("0.054321")).returnRate(new BigDecimal(rate)).exitReason("MANUAL").build();
    }

    @Test
    void smallLossAndTrailingPeakSurviveDatabaseRoundTrip() {
        try (var context = open("create")) {
            var repo = context.getBean(PaperPositionRepository.class);
            var saved = repo.saveAndFlush(position("-0.000123"));
            var reloaded = repo.findById(saved.getId()).orElseThrow();
            assertThat(reloaded.getReturnRate()).isEqualByComparingTo("-0.000123");
            assertThat(reloaded.getPeakRate()).isEqualByComparingTo("0.054321");
        }
    }

    @Test
    void legacySchemaUpgradePreservesOldTradesAndNewPrecisionAcrossRestart() throws Exception {
        try (var connection = DriverManager.getConnection(url(), "sa", ""); var sql = connection.createStatement()) {
            sql.execute("""
                    CREATE TABLE paper_position (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      symbol VARCHAR(255) NOT NULL, entry_date DATE NOT NULL, entry_price NUMERIC(38,2) NOT NULL,
                      status VARCHAR(255) NOT NULL, peak_rate NUMERIC(38,2) NOT NULL,
                      exit_date DATE, exit_price NUMERIC(38,2), return_rate NUMERIC(38,2), exit_reason VARCHAR(255),
                      quick5reached BOOLEAN, quick5exit_date DATE, quick5exit_price NUMERIC(38,2))
                    """);
            sql.execute("""
                    INSERT INTO paper_position (symbol, entry_date, entry_price, status, peak_rate, return_rate)
                    VALUES ('OLD', DATE '2026-10-01', 100, 'CLOSED', 0.05, 0.01)
                    """);
        }
        long newId;
        try (var context = open("update")) {
            var repo = context.getBean(PaperPositionRepository.class);
            var old = repo.findById(1L).orElseThrow();
            assertThat(old.getSymbol()).isEqualTo("OLD");
            assertThat(old.getEntryPrice()).isEqualByComparingTo("100");
            assertThat(old.getReturnRate()).isEqualByComparingTo("0.01");
            assertThat(old.getPeakRate()).isEqualByComparingTo("0.05");
            newId = repo.saveAndFlush(position("0.012345")).getId();
        }
        try (var context = open("validate")) {
            var repo = context.getBean(PaperPositionRepository.class);
            assertThat(repo.count()).isEqualTo(2);
            var reloaded = repo.findById(newId).orElseThrow();
            assertThat(reloaded.getReturnRate()).isEqualByComparingTo("0.012345");
            assertThat(reloaded.getPeakRate()).isEqualByComparingTo("0.054321");
        }
    }
}
