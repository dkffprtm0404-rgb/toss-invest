package com.tossinvest.tossinvestbackend.scalping;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.autoconfigure.domain.EntityScan;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.annotation.Configuration;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;

import java.math.BigDecimal;
import java.nio.file.Path;
import java.sql.DriverManager;
import java.time.LocalDateTime;

import static org.assertj.core.api.Assertions.assertThat;

class ScalpingSchemaUpgradeTests {
    @TempDir Path directory;

    @Configuration(proxyBeanMethods = false)
    @EnableAutoConfiguration
    @EntityScan(basePackageClasses = ScalpingPosition.class)
    @EnableJpaRepositories(basePackageClasses = ScalpingPositionRepository.class)
    static class App {}

    @Test
    void updatePreservesExistingRowsAndWidensRateColumns() throws Exception {
        String url = "jdbc:h2:file:" + directory.resolve("scalping").toAbsolutePath();
        try (var connection = DriverManager.getConnection(url, "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE scalping_position (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      symbol VARCHAR(255) NOT NULL, entry_time TIMESTAMP(6) NOT NULL,
                      entry_price NUMERIC(38,2) NOT NULL, status VARCHAR(255) NOT NULL,
                      peak_rate NUMERIC(38,2) NOT NULL, return_rate NUMERIC(38,2),
                      exit_time TIMESTAMP(6), exit_price NUMERIC(38,2), exit_reason VARCHAR(255),
                      ema5_at_entry NUMERIC(38,2), ema20_at_entry NUMERIC(38,2))
                    """);
            statement.execute("""
                    INSERT INTO scalping_position (symbol, entry_time, entry_price, status, peak_rate, return_rate)
                    VALUES ('005930', TIMESTAMP '2026-10-07 10:00:00', 100, 'CLOSED', 0.01, -0.01)
                    """);
        }
        try (var context = new SpringApplicationBuilder(App.class).web(WebApplicationType.NONE).run(
                "--spring.datasource.url=" + url, "--spring.datasource.username=sa", "--spring.datasource.password=",
                "--spring.jpa.hibernate.ddl-auto=update", "--spring.jpa.show-sql=false", "--spring.main.banner-mode=off")) {
            var repo = context.getBean(ScalpingPositionRepository.class);
            assertThat(repo.findAll()).singleElement().satisfies(old -> {
                assertThat(old.getSymbol()).isEqualTo("005930");
                assertThat(old.getPeakRate()).isEqualByComparingTo("0.01");
                assertThat(old.getReturnRate()).isEqualByComparingTo("-0.01");
            });
            var saved = repo.saveAndFlush(ScalpingPosition.builder().symbol("000660")
                    .entryTime(LocalDateTime.of(2026, 10, 8, 10, 0)).entryPrice(new BigDecimal("100"))
                    .peakRate(new BigDecimal("0.0091")).returnRate(new BigDecimal("-0.006")).build());
            var reloaded = repo.findById(saved.getId()).orElseThrow();
            assertThat(reloaded.getPeakRate()).isEqualByComparingTo("0.0091");
            assertThat(reloaded.getReturnRate()).isEqualByComparingTo("-0.006");
        }
    }
}
